"""Evaluate entity and duplicate alignment against generator truth.

The truth file is generated by ``generate_synthea_sites.py`` and represents
synthetic ground truth only.  This evaluator never labels it as a clinical
expert gold standard.
"""

from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, Iterable, List, Mapping, Optional, Sequence, Tuple

import numpy as np

from alignment_aware import canonical_event, event_fingerprint, load_linkage_profiles, mutual_best_links, profile_score_blocks


def first(row: Mapping[str, Any], *names: str) -> Any:
    for name in names:
        if row.get(name) not in (None, ""):
            return row[name]
    return None


def normalize_code(value: Any, aligned: bool) -> Optional[str]:
    if value in (None, ""):
        return None
    code = re.sub(r"\s+", "", str(value).casefold())
    if aligned:
        code = re.sub(r"^l\d+-", "", code)
    return code


def load_sites(sites_dir: Path) -> Dict[Tuple[str, str], List[Mapping[str, Any]]]:
    profiles: Dict[Tuple[str, str], List[Mapping[str, Any]]] = defaultdict(list)
    for path in sorted(sites_dir.glob("site_*.jsonl")):
        with path.open("r", encoding="utf-8") as handle:
            for line in handle:
                if not line.strip():
                    continue
                row = json.loads(line)
                site = str(first(row, "site_id") or path.stem)
                patient = first(row, "patient_id", "patientId")
                if patient in (None, ""):
                    continue
                profiles[(site, str(patient))].append(row)
    return profiles


def load_truth(path: Path) -> Dict[Tuple[str, str], str]:
    mapping: Dict[Tuple[str, str], str] = {}
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            row = json.loads(line)
            site, patient, gold = row.get("site_id"), row.get("patient_id"), row.get("gold_patient_id")
            if site and patient and gold:
                mapping[(str(site), str(patient))] = str(gold)
    return mapping


def token_set(rows: Iterable[Mapping[str, Any]], aligned: bool) -> set[str]:
    tokens: set[str] = set()
    for row in rows:
        event_type = first(row, "event_type", "eventType", "type")
        if event_type:
            tokens.add(f"type:{str(event_type).casefold()}")
        code = normalize_code(first(row, "concept_code", "local_code", "code"), aligned)
        if code:
            tokens.add(f"code:{code}")
        label = first(row, "label", "description")
        if label:
            tokens.add(f"label:{str(label).casefold()}")
    return tokens


def pair_score(left: set[str], right: set[str]) -> float:
    union = left | right
    return len(left & right) / len(union) if union else 0.0


def evaluate_entity_alignment(sites: Mapping[Tuple[str, str], Sequence[Mapping[str, Any]]],
                              truth: Mapping[Tuple[str, str], str], threshold: float,
                              aligned: bool) -> Dict[str, Any]:
    keys = sorted(set(sites) & set(truth))
    profiles = {key: token_set(sites[key], aligned) for key in keys}
    pair_count = 0
    tp = fp = fn = tn = 0
    for left_keys, right_keys, scores in profile_score_blocks(profiles):
        left_gold = np.array([truth[key] for key in left_keys])
        right_gold = np.array([truth[key] for key in right_keys])
        actual = left_gold[:, None] == right_gold[None, :]
        predicted = scores >= threshold
        pair_count += int(scores.size)
        tp += int(np.sum(actual & predicted))
        fp += int(np.sum(~actual & predicted))
        fn += int(np.sum(actual & ~predicted))
        tn += int(np.sum(~actual & ~predicted))
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {
        "aligned": aligned, "threshold": threshold, "pairs": pair_count,
        "true_positive": tp, "false_positive": fp, "false_negative": fn, "true_negative": tn,
        "precision": precision, "recall": recall, "f1": f1,
        "synthetic_ground_truth": True,
    }


def evaluate_mutual_best(sites: Mapping[Tuple[str, str], Sequence[Mapping[str, Any]]],
                         truth: Mapping[Tuple[str, str], str], threshold: float = 0.5) -> Dict[str, Any]:
    """Match only unique, mutually best cross-site profiles above threshold."""
    keys = sorted(set(sites) & set(truth))
    profiles = {key: token_set(sites[key], aligned=True) for key in keys}
    edges, audit = mutual_best_links(profiles, threshold)
    candidate_pairs = audit["candidate_pairs"]
    by_gold = defaultdict(list)
    for key in keys:
        by_gold[truth[key]].append(key)
    truth_pairs = sum(sum(left[0] != right[0] for idx, left in enumerate(group) for right in group[idx + 1:])
                      for group in by_gold.values())
    predicted_pairs = len(edges)
    tp = sum(truth[left] == truth[right] for left, right, _score in edges)
    fp = predicted_pairs - tp
    fn = truth_pairs - tp
    precision = tp / predicted_pairs if predicted_pairs else 0.0
    recall = tp / truth_pairs if truth_pairs else 0.0
    return {"method": "mutual_unique_best_jaccard", "aligned": True, "threshold": threshold,
            "pairs": candidate_pairs, "predicted_pairs": predicted_pairs,
            "true_positive": tp, "false_positive": fp, "false_negative": fn,
            "true_negative": candidate_pairs - truth_pairs - fp,
            "precision": precision, "recall": recall,
            "f1": 2 * precision * recall / (precision + recall) if precision + recall else 0.0,
            "synthetic_ground_truth": True}


def evaluate_duplicates(sites_dir: Path, truth_path: Path) -> Dict[str, Any]:
    total = 0
    detected = 0
    tp = 0
    missing_patient_records = 0
    truth_duplicate_ids: set[Tuple[str, str]] = set()
    with truth_path.open("r", encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                truth_row = json.loads(line)
                if truth_row.get("duplicate_of"):
                    truth_duplicate_ids.add((str(truth_row["site_id"]), str(truth_row["event_id"])))
    truth_positive = len(truth_duplicate_ids)
    for path in sorted(sites_dir.glob("site_*.jsonl")):
        seen: Dict[Tuple[Any, ...], str] = {}
        with path.open("r", encoding="utf-8") as handle:
            for line in handle:
                if not line.strip():
                    continue
                row = json.loads(line)
                total += 1
                event_id = str(first(row, "event_id", "eventId") or "")
                truth_dup = (str(first(row, "site_id") or path.stem), event_id) in truth_duplicate_ids
                event = canonical_event(row, total)
                if event["patient_id"] is None:
                    missing_patient_records += 1
                    continue
                key = event_fingerprint(event)
                predicted = key in seen
                detected += int(predicted)
                tp += int(predicted and truth_dup)
                seen[key] = event_id or str(total)
    precision = tp / detected if detected else 0.0
    recall = tp / truth_positive if truth_positive else 0.0
    return {"records": total, "truth_duplicates": truth_positive, "detected_duplicates": detected,
            "unresolved_missing_patient_records": missing_patient_records,
            "precision": precision, "recall": recall,
            "f1": 2 * precision * recall / (precision + recall) if precision + recall else 0.0,
            "synthetic_ground_truth": True}


def evaluate_feature_linkage(sites_dir: Path, truth: Mapping[Tuple[str, str], str],
                             threshold: float = 0.5) -> Dict[str, Any]:
    profiles = load_linkage_profiles(sorted(sites_dir.glob("site_*.jsonl")))
    edges, audit = mutual_best_links(profiles, threshold)
    mapped_truth = {(f"site_{site.split('-')[-1]}", patient): gold for (site, patient), gold in truth.items()}
    groups = defaultdict(list)
    for key in profiles:
        if key in mapped_truth:
            groups[mapped_truth[key]].append(key)
    truth_pairs = sum(sum(left[0] != right[0] for idx, left in enumerate(group) for right in group[idx + 1:])
                      for group in groups.values())
    tp = sum(mapped_truth.get(left) is not None and mapped_truth.get(left) == mapped_truth.get(right)
             for left, right, _score in edges)
    precision = tp / len(edges) if edges else 0.0
    recall = tp / truth_pairs if truth_pairs else 0.0
    return {**audit, "method": "noncondition_mutual_best", "true_positive": tp,
            "false_positive": len(edges) - tp, "false_negative": truth_pairs - tp,
            "precision": precision, "recall": recall,
            "f1": 2 * precision * recall / (precision + recall) if precision + recall else 0.0,
            "synthetic_ground_truth": True}


def evaluate(truth_path: Path, sites_dir: Path, threshold: float = 0.5) -> Dict[str, Any]:
    sites = load_sites(sites_dir)
    truth = load_truth(truth_path)
    return {
        "truth_path": str(truth_path), "sites_dir": str(sites_dir),
        "entity_alignment": {
            "raw": evaluate_entity_alignment(sites, truth, threshold, aligned=False),
            "aligned": evaluate_entity_alignment(sites, truth, threshold, aligned=True),
            "mutual_best": evaluate_mutual_best(sites, truth, threshold),
            "noncondition_mutual_best": evaluate_feature_linkage(sites_dir, truth, threshold),
        },
        "duplicate_detection": evaluate_duplicates(sites_dir, truth_path),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--truth", type=Path, required=True)
    parser.add_argument("--sites-dir", type=Path, required=True)
    parser.add_argument("--threshold", type=float, default=0.5)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = evaluate(args.truth, args.sites_dir, args.threshold)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"output": str(args.output), "entity_alignment": result["entity_alignment"]}, ensure_ascii=False))


if __name__ == "__main__":
    main()
